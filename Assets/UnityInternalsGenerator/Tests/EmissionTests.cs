        private static GenerationResult Generate(NamingStyle naming = NamingStyle.Exact)
        {
            var input = new GenerationInput(new[] { typeof(FixtureMarker).Assembly }, c_Host, naming, null, "test");
            return WrapperGenerator.Generate(input);
