        [Test]
        public void FilePathCollision_DropsBothTypes_AndReportsNameCollision()
        {
            var result = Generate();
            CollectionAssert.DoesNotContain(result.Files.Select(f => f.RelativePath.ToLowerInvariant()), "wrappedunityinternalsfixture/casetwin.g.cs");
            foreach (var name in new[] { "CaseTwin", "Casetwin" })
            {
                var entry = result.Entries.Single(e => e.Id.EndsWith("|UnityInternalsFixture." + name + "|Type|" + name));
                Assert.AreEqual(WrapStatus.NameCollision, entry.Status);
                StringAssert.StartsWith("file path collision: ", entry.Reason);
            }
        }

        [Test]
        public void CollidingGroups_GroupsByPathIgnoringCase()
        {
            var groups = WrapperGenerator.CollidingGroups(new[] { "a/X.g.cs", "a/x.g.cs", "b/Y.g.cs" }, s => s);
            Assert.AreEqual(1, groups.Count);
            CollectionAssert.AreEqual(new[] { "a/X.g.cs", "a/x.g.cs" }, groups[0]);
            Assert.AreEqual(0, WrapperGenerator.CollidingGroups(new[] { "a", "b" }, s => s).Count);
        }

