        private static GeneratedFile File(GenerationResult result, string relativePath)
        {
            var file = result.Files.FirstOrDefault(f => f.RelativePath == relativePath);
            Assert.IsNotNull(file, "Missing file " + relativePath + "; have: " + string.Join(", ", result.Files.Select(f => f.RelativePath)));
            return file;
        }

        // Id layout: Assembly|Type|Kind|Name(Params)
        private static ReportEntry Entry(GenerationResult result, string typeFullName, string kind, string name)
        {
            var matches = result.Entries.Where(e =>
            {
                var parts = e.Id.Split('|');
                if (parts.Length != 4 || parts[1] != typeFullName || parts[2] != kind) return false;
                var paren = parts[3].IndexOf('(');
                return (paren < 0 ? parts[3] : parts[3].Substring(0, paren)) == name;
            }).ToList();
            Assert.AreEqual(1, matches.Count, "Expected exactly one entry for " + typeFullName + " " + kind + " " + name);
            return matches[0];
        }

        private static void AssertContainsLine(GeneratedFile file, string line)
        {
            var lines = file.Content.Split('\n');
            Assert.IsTrue(lines.Contains(line), "Missing line:\n" + line + "\n--- in ---\n" + file.Content);
        }

