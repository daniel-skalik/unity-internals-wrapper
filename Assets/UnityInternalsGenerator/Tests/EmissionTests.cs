        [Test]
        public void Entries_MemberStatuses()
        {
            var result = Generate();
            Assert.AreEqual(WrapStatus.Deferred, Entry(result, c_Api, "Method", "WithRef").Status);
            Assert.AreEqual(WrapStatus.Deferred, Entry(result, c_Api, "Method", "Echo``1").Status);
            Assert.AreEqual("GenericMethod (step 3)", Entry(result, c_Api, "Method", "Echo``1").Reason);
            Assert.AreEqual(WrapStatus.Deferred, Entry(result, c_Api, "Method", "MakeHolder").Status);
            Assert.AreEqual("WrapperConversion (step 2)", Entry(result, c_Api, "Method", "MakeHolder").Reason);
            Assert.AreEqual(WrapStatus.Excluded, Entry(result, c_Api, "Method", "Dead").Status);
            Assert.AreEqual("ObsoleteError", Entry(result, c_Api, "Method", "Dead").Reason);
            Assert.AreEqual(WrapStatus.NotAccessible, Entry(result, c_Api, "Method", "Hidden").Status);
            Assert.AreEqual(WrapStatus.Deferred, Entry(result, c_Api, "Method", "WithNullableMask").Status);
            Assert.AreEqual(WrapStatus.Deferred, Entry(result, c_Api, "Event", "Changed").Status);
            Assert.AreEqual("Event (step 3)", Entry(result, c_Api, "Event", "Changed").Reason);
            Assert.AreEqual(WrapStatus.Excluded, Entry(result, c_Api, "Field", "<Current>k__BackingField").Status);
            Assert.AreEqual(WrapStatus.Excluded, Entry(result, c_Api, "Ctor", ".cctor").Status);

            Assert.AreEqual(WrapStatus.Wrapped, Entry(result, c_Api, "Method", "Add").Status);
            Assert.AreEqual(WrapStatus.Wrapped, Entry(result, c_Api, "Property", "Current").Status);
            Assert.AreEqual(WrapStatus.Wrapped, Entry(result, c_Api, "Const", "Answer").Status);
            Assert.AreEqual(WrapStatus.Wrapped, Entry(result, c_Api, "Field", "Counter").Status);
            var withDate = Entry(result, c_Api, "Method", "WithDate");
            Assert.AreEqual(WrapStatus.Wrapped, withDate.Status);
            Assert.AreEqual("default dropped", withDate.Reason);

            var holder = "UnityInternalsFixture.Holder";
            Assert.AreEqual(WrapStatus.Deferred, Entry(result, holder, "Property", "InstanceValue").Status);
            Assert.AreEqual("InstanceMembers (step 2)", Entry(result, holder, "Property", "InstanceValue").Reason);
            Assert.AreEqual(WrapStatus.Deferred, Entry(result, holder, "Ctor", ".ctor").Status);
            Assert.AreEqual("Operator (step 3)", Entry(result, holder, "Method", "op_Addition").Reason);
            Assert.AreEqual(WrapStatus.Wrapped, Entry(result, holder, "Property", "StaticValue").Status);
        }

        [Test]
        public void Entries_AccessorsCoveredByProperty_AndIdsUnique()
        {
            var result = Generate();
            var ids = result.Entries.Select(e => e.Id).ToList();
            Assert.IsFalse(ids.Any(i => i.Contains("|Method|get_") || i.Contains("|Method|set_") || i.Contains("|Method|add_") || i.Contains("|Method|remove_")));
            Assert.AreEqual(ids.Count, ids.Distinct().Count());
            CollectionAssert.AreEqual(ids.OrderBy(i => i, StringComparer.Ordinal).ToList(), ids);
        }

        [Test]
        public void Naming_PascalCase_CollisionsReported()
        {
            var result = Generate(NamingStyle.PascalCase);
            Assert.AreEqual(WrapStatus.NameCollision, Entry(result, "UnityInternalsFixture.Collide", "Field", "value").Status);
            Assert.AreEqual(WrapStatus.NameCollision, Entry(result, "UnityInternalsFixture.Collide", "Field", "Value").Status);
            Assert.AreEqual(WrapStatus.NameCollision, Entry(result, "UnityInternalsFixture.Clash", "Field", "clash").Status);
            var overloads = result.Entries.Where(e => e.Id.Contains("|" + c_Api + "|Method|Overload(")).ToList();
            Assert.AreEqual(2, overloads.Count);
            Assert.IsTrue(overloads.All(e => e.Status == WrapStatus.Wrapped));
            // Both members collide, so Collide has nothing to emit and gets no file.
            CollectionAssert.DoesNotContain(result.Files.Select(f => f.RelativePath).ToList(), "WrappedUnityInternalsFixture/Collide.g.cs");
        }

        [Test]
        public void Naming_Exact_NoCollisions()
        {
            var result = Generate();
