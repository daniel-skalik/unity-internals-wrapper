        [Test]
        public void LineOwners_MapToTypeAndMemberIds()
        {
            var file = File(Generate(), "WrappedUnityInternalsFixture/StaticApi.g.cs");
            var api = typeof(FixtureMarker).Assembly.GetType(c_Api, true);
            var lines = file.Content.Split('\n');
            var addLine = Array.FindIndex(lines, l => l.Contains(" Add(")) + 1;
            Assert.AreEqual(MemberId.Member(api.GetMethod("Add", System.Reflection.BindingFlags.Static | System.Reflection.BindingFlags.NonPublic)), file.MemberAt(addLine));
            var classLine = Array.FindIndex(lines, l => l.Contains("public static class StaticApi")) + 1;
            Assert.AreEqual(MemberId.Type(api), file.MemberAt(classLine));
            var nestedValueLine = Array.FindIndex(lines, l => l.Contains("X = 0,")) + 1;
            StringAssert.Contains("StaticApi+Nested", file.MemberAt(nestedValueLine));
            Assert.IsNull(file.MemberAt(1));
        }

        [Test]
        public void Generate_IsDeterministic()
        {
            var a = Generate();
            var b = Generate();
            CollectionAssert.AreEqual(a.Files.Select(f => f.RelativePath).ToList(), b.Files.Select(f => f.RelativePath).ToList());
            for (var i = 0; i < a.Files.Count; i++)
            {
                CollectionAssert.AreEqual(System.Text.Encoding.UTF8.GetBytes(a.Files[i].Content), System.Text.Encoding.UTF8.GetBytes(b.Files[i].Content), a.Files[i].RelativePath);
            }
            CollectionAssert.AreEqual(a.Entries.Select(e => e.Id + "/" + e.Status + "/" + e.Reason).ToList(), b.Entries.Select(e => e.Id + "/" + e.Status + "/" + e.Reason).ToList());
        }
