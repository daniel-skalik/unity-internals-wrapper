        [Test]
        public void DerivedWrapper_MirrorsBase_HidesWithNew()
        {
            var result = Generate();
            var twig = File(result, "WrappedUnityInternalsFixture/Twig.g.cs");
            AssertContainsLine(twig, "    public class Twig : global::WrappedUnityInternalsFixture.Branch");
            AssertContainsLine(twig, "        internal new readonly global::UnityInternalsFixture.Twig m_Value;");
            AssertContainsLine(twig, "        internal Twig(global::UnityInternalsFixture.Twig value) : base(value) { m_Value = value; }");
            AssertContainsLine(twig, "        public new string Describe() => m_Value.Describe();");
            AssertContainsLine(twig, "        public Twig(int size) : this(new global::UnityInternalsFixture.Twig(size)) { }");

            // Only the root declares Target, the conversion and the equality members.
            StringAssert.DoesNotContain("Target", twig.Content);
            StringAssert.DoesNotContain("operator ==", twig.Content);

            AssertContainsLine(File(result, "WrappedUnityInternalsFixture/Leaf.g.cs"), "    public class Leaf : global::WrappedUnityInternalsFixture.Twig");
        }

        [Test]
        public void InterfaceWrapper_IsAClassOverTheInterfaceValue()
        {
            var thing = File(Generate(), "WrappedUnityInternalsFixture/IThing.g.cs");
            AssertContainsLine(thing, "    public class IThing");
            AssertContainsLine(thing, "        internal readonly global::UnityInternalsFixture.IThing m_Value;");
            AssertContainsLine(thing, "        internal static IThing Wrap(global::UnityInternalsFixture.IThing value) => value == null ? null : new IThing(value);");
            AssertContainsLine(thing, "        public int Value => m_Value.Value;");
            AssertContainsLine(thing, "        public string Describe() => m_Value.Describe();");
            StringAssert.DoesNotContain("Target", thing.Content);
            StringAssert.DoesNotContain("implicit operator", thing.Content);
        }

        [Test]
        public void Registry_RegistersEveryEmittedClassWrapper_Ordinal()
        {
            var registry = File(Generate(), WrapperSyntaxPath());
            AssertContainsLine(registry, "    public static class WrapperRegistry");
            AssertContainsLine(registry, "        public static object Wrap(object value)");
            AssertContainsLine(registry, "                if (s_Factories.TryGetValue(type, out var factory)) return factory(value);");
            foreach (var name in new[] { "Branch", "Twig", "Leaf", "Holder", "Thing", "AbstractThing" })
            {
                AssertContainsLine(registry, "            map[typeof(global::UnityInternalsFixture." + name + ")] = value => new global::WrappedUnityInternalsFixture." + name + "((global::UnityInternalsFixture." + name + ")value);");
            }

            // Structs and interfaces wrap directly, so they are not registered.
            StringAssert.DoesNotContain("typeof(global::UnityInternalsFixture.Point)", registry.Content);
            StringAssert.DoesNotContain("typeof(global::UnityInternalsFixture.IThing)", registry.Content);

            var registrations = registry.Content.Split('\n').Where(l => l.Contains("map[typeof(")).ToList();
            CollectionAssert.AreEqual(registrations.OrderBy(l => l, StringComparer.Ordinal).ToList(), registrations);
        }

        [Test]
        public void Registry_LinesOwnedByTheirType_AndAbsentWithoutClassWrappers()
        {
            var result = Generate();
            var registry = File(result, WrapperSyntaxPath());
            var lines = registry.Content.Split('\n');
            var branchLine = Array.FindIndex(lines, l => l.Contains("map[typeof(global::UnityInternalsFixture.Branch)]")) + 1;
            Assert.AreEqual(MemberId.Type(Fixture("Branch")), registry.MemberAt(branchLine));

            var enumsOnly = Generate(new SelectionRules(new[] { MemberId.Type(Fixture("Mask")) }, Array.Empty<string>()));
            CollectionAssert.DoesNotContain(enumsOnly.Files.Select(f => f.RelativePath).ToList(), WrapperSyntaxPath());
        }

        [Test]
        public void ReservedNames_ReportedAsCollisions()
        {
            var result = Generate();
            var reserved = Fixture("ReservedNames");
            var wrap = Entry(result, MemberId.Member(reserved.GetMethod("Wrap", c_Declared)));
            Assert.AreEqual(WrapStatus.NameCollision, wrap.Status);
            StringAssert.Contains("reserved by the wrapper", wrap.Reason);
            Assert.AreEqual(WrapStatus.NameCollision, Entry(result, MemberId.Member(reserved.GetProperty("Target", c_Declared))).Status);
            Assert.AreEqual(WrapStatus.Wrapped, Entry(result, MemberId.Member(reserved.GetProperty("Fine", c_Declared))).Status);

            var file = File(result, "WrappedUnityInternalsFixture/ReservedNames.g.cs");
            AssertContainsLine(file, "        public int Fine => m_Value.Fine;");
            StringAssert.DoesNotContain("Fine()", file.Content);
        }

        [Test]
        public void AbstractType_ConstructorDeferredToStep6_MembersStillWrapped()
        {
            var result = Generate();
            var abstractThing = Fixture("AbstractThing");
            var ctor = Entry(result, MemberId.Member(abstractThing.GetConstructors(c_Declared).Single()));
            Assert.AreEqual(WrapStatus.Deferred, ctor.Status);
            Assert.AreEqual("Inheritable (step 6)", ctor.Reason);

            var file = File(result, "WrappedUnityInternalsFixture/AbstractThing.g.cs");
            AssertContainsLine(file, "    public class AbstractThing");
            AssertContainsLine(file, "        public int Kind() => m_Value.Kind();");
            StringAssert.DoesNotContain("public AbstractThing(", file.Content);
        }

        [Test]
        public void RetiredDeferredReasons_AreGone()
        {
            var reasons = Generate().Entries.Select(e => e.Reason).Where(r => r != null).Distinct(StringComparer.Ordinal).ToList();
            foreach (var retired in new[] { "InstanceMembers (step 2)", "Struct wrapper (step 2)", "Interface wrapper (step 2)", "Indexer (step 2)", "WrapperConversion (step 2)" })
            {
                CollectionAssert.DoesNotContain(reasons, retired);
            }
        }

        [Test]
        public void StillDeferredOrUnsupported_CarryAReason()
        {
            var result = Generate();
            foreach (var e in result.Entries.Where(e => e.Status == WrapStatus.Deferred || e.Status == WrapStatus.Unsupported))
            {
                Assert.IsFalse(string.IsNullOrEmpty(e.Reason), e.Id);
            }

            var staticApi = "DandaUtils.UnityInternalsGenerator.Tests.Fixture|UnityInternalsFixture.StaticApi|";
            Assert.AreEqual("ref/out (step 3)", result.Entries.Single(e => e.Id.StartsWith(staticApi + "Method|WithRef(", StringComparison.Ordinal)).Reason);
            Assert.AreEqual("Delegate wrapper (step 3)", Entry(result, MemberId.Type(Fixture("Callback"))).Reason);
            Assert.AreEqual("Event (step 3)", result.Entries.Single(e => e.Id == staticApi + "Event|Changed").Reason);
        }

        [Test]
        public void Selection_MemberNeedingAWrappedType_AutoIncludesIt()
        {
            var shift = MemberId.Member(Fixture("StaticApi").GetMethod("Shift", BindingFlags.Static | BindingFlags.NonPublic));
            var result = WrapperGenerator.Generate(Input(new SelectionRules(new[] { shift }, Array.Empty<string>())));

            CollectionAssert.Contains(result.Selection.EmittedTypeIds, MemberId.Type(Fixture("Point")));
            Assert.AreEqual(shift, result.Selection.AutoIncludedBy[MemberId.Type(Fixture("Point"))]);
            CollectionAssert.Contains(result.Files.Select(f => f.RelativePath).ToList(), "WrappedUnityInternalsFixture/Point.g.cs");
        }

        [Test]
        public void Selection_ConstructorNeedingAWrappedType_AutoIncludesIt()
        {
            var catalog = WrapperGenerator.BuildCatalog(Input());
            var indexer = catalog.ChildrenOf(MemberId.Type(Fixture("Branch"))).Single(n => n.Kind == NodeKind.Indexer);
            Assert.AreEqual(WrapStatus.Wrapped, indexer.Status);

            var corner = catalog.ChildrenOf(MemberId.Type(Fixture("Branch"))).Single(n => n.Name == "Corner");
            var result = WrapperGenerator.Generate(Input(new SelectionRules(new[] { corner.Id }, Array.Empty<string>())));
            Assert.AreEqual(corner.Id, result.Selection.AutoIncludedBy[MemberId.Type(Fixture("Point"))]);
        }

        [Test]
        public void Generate_IsDeterministic_IncludingTheRegistry()
        {
            var a = Generate();
            var b = Generate();
            CollectionAssert.AreEqual(a.Files.Select(f => f.RelativePath).ToList(), b.Files.Select(f => f.RelativePath).ToList());
            for (var i = 0; i < a.Files.Count; i++)
            {
                Assert.AreEqual(a.Files[i].Content, b.Files[i].Content, a.Files[i].RelativePath);
            }
        }

        private static string WrapperSyntaxPath() => "WrappedRuntime/WrapperRegistry.g.cs";
    }
