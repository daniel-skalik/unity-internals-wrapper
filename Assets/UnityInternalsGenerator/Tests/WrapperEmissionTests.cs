        private static GenerationResult Generate(SelectionRules selection = null) => WrapperGenerator.Generate(Input(selection));

        private static GenerationInput Input(SelectionRules selection = null) => new GenerationInput(new[] { typeof(FixtureMarker).Assembly }, c_Host, NamingStyle.Exact, selection, "test");

        private static Type Fixture(string name) => typeof(FixtureMarker).Assembly.GetType("UnityInternalsFixture." + name, true);

        private static GeneratedFile File(GenerationResult result, string relativePath)
        {
            var file = result.Files.FirstOrDefault(f => f.RelativePath == relativePath);
            Assert.IsNotNull(file, "Missing file " + relativePath + "; have: " + string.Join(", ", result.Files.Select(f => f.RelativePath)));
            return file;
        }

        private static void AssertContainsLine(GeneratedFile file, string line)
        {
            Assert.IsTrue(file.Content.Split('\n').Contains(line), "Missing line:\n" + line + "\n--- in ---\n" + file.Content);
        }

        private static ReportEntry Entry(GenerationResult result, string id)
        {
            var entry = result.Entries.FirstOrDefault(e => e.Id == id);
            Assert.IsNotNull(entry, "No entry for " + id);
            return entry;
        }

        [Test]
        public void Struct_File_ExactContent()
        {
            Assert.AreEqual(c_PointFile, File(Generate(), "WrappedUnityInternalsFixture/Point.g.cs").Content);
        }

        [Test]
        public void ClassWrapper_Storage_TargetAndEquality()
        {
            var branch = File(Generate(), "WrappedUnityInternalsFixture/Branch.g.cs");
            foreach (var line in new[]
            {
                "    public class Branch",
                "        internal readonly global::UnityInternalsFixture.Branch m_Value;",
                "        internal Branch(global::UnityInternalsFixture.Branch value) { m_Value = value; }",
                "        internal static Branch Wrap(global::UnityInternalsFixture.Branch value) => value == null ? null : global::WrappedRuntime.WrapperRegistry.Wrap(value) as Branch ?? new Branch(value);",
                "        public global::UnityInternalsFixture.FixtureNode Target => m_Value;",
                "        public static implicit operator global::UnityInternalsFixture.FixtureNode(Branch wrapper) => wrapper?.m_Value;",
                "        public override bool Equals(object obj) => obj is Branch other && global::System.Object.ReferenceEquals(m_Value, other.m_Value);",
                "        public override int GetHashCode() => m_Value.GetHashCode();",
                "        public static bool operator ==(Branch left, Branch right) => global::System.Object.ReferenceEquals(left, null) ? global::System.Object.ReferenceEquals(right, null) : left.Equals(right);",
                "        public static bool operator !=(Branch left, Branch right) => (left == right) == false;",
            })
            {
                AssertContainsLine(branch, line);
            }
        }

