namespace DandaUtils.Editor.UnityInternalsGenerator.Tests
{
    using System;
    using System.Linq;
    using System.Reflection;
    using DandaUtils.Editor.UnityInternalsGenerator.Emit;
    using DandaUtils.Editor.UnityInternalsGenerator.Model;
    using DandaUtils.Editor.UnityInternalsGenerator.Naming;
    using DandaUtils.Editor.UnityInternalsGenerator.Pipeline;
    using DandaUtils.Editor.UnityInternalsGenerator.Selection;
    using NUnit.Framework;
    using UnityInternalsFixture;

    /// <summary>Step 4: a public Unity type with accessible-internal members gets a wrapper that mirrors only those members.</summary>
    public sealed class PublicTypeTests
    {
        private const string c_Host = "Wrapped.Fixture.Host";
        private const BindingFlags c_Declared = BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
        private const string c_RetiredReason = "PublicTypeInternalMembers (step 4)";

        private const string c_Header =
            "// <auto-generated>\n" +
            "// Generated by DandaUtils.UnityInternalsGenerator v1 for Unity test. Do not edit.\n" +
            "// </auto-generated>\n" +
            "#pragma warning disable 0612, 0618\n";

        /// <summary>Static host: only the internal member is forwarded, there is no value field and no constructor.</summary>
        private const string c_ApiFile = c_Header +
            "namespace WrappedUnityInternalsFixture\n" +
            "{\n" +
            "    public static class PublicApi\n" +
            "    {\n" +
            "        public static void Hidden() => global::UnityInternalsFixture.PublicApi.Hidden();\n" +
            "    }\n" +
            "}\n";

        /// <summary>Internal nested type of a public type, emitted inside the public type's wrapper.</summary>
        private const string c_HostFile = c_Header +
            "namespace WrappedUnityInternalsFixture\n" +
            "{\n" +
            "    public static class PublicHost\n" +
            "    {\n" +
            "        public enum InnerMode : int\n" +
            "        {\n" +
            "            A = 0,\n" +
            "        }\n" +
            "    }\n" +
            "}\n";

        /// <summary>Struct host: Target plus both conversions, and the internal field written through.</summary>
        private const string c_SpotFile = c_Header +
            "namespace WrappedUnityInternalsFixture\n" +
            "{\n" +
            "    public struct PublicSpot\n" +
            "    {\n" +
            "        internal global::UnityInternalsFixture.PublicSpot m_Value;\n" +
            "\n" +
            "        internal PublicSpot(global::UnityInternalsFixture.PublicSpot value) { m_Value = value; }\n" +
            "\n" +
            "        internal static PublicSpot Wrap(global::UnityInternalsFixture.PublicSpot value) => new PublicSpot(value);\n" +
            "\n" +
            "        public global::UnityInternalsFixture.PublicSpot Target => m_Value;\n" +
            "\n" +
            "        public static implicit operator global::UnityInternalsFixture.PublicSpot(PublicSpot wrapper) => wrapper.m_Value;\n" +
            "\n" +
            "        public static implicit operator PublicSpot(global::UnityInternalsFixture.PublicSpot value) => Wrap(value);\n" +
            "\n" +
            "        public override bool Equals(object obj) => obj is PublicSpot other && m_Value.Equals(other.m_Value);\n" +
            "\n" +
            "        public override int GetHashCode() => m_Value.GetHashCode();\n" +
            "\n" +
            "        public static bool operator ==(PublicSpot left, PublicSpot right) => left.m_Value.Equals(right.m_Value);\n" +
            "\n" +
            "        public static bool operator !=(PublicSpot left, PublicSpot right) => (left == right) == false;\n" +
            "\n" +
            "        public int Value { get => m_Value.Value; set => m_Value.Value = value; }\n" +
            "\n" +
            "        public int Twice() => m_Value.Twice();\n" +
            "    }\n" +
            "}\n";

        private static GenerationResult Generate(SelectionRules selection = null) => WrapperGenerator.Generate(Input(selection));

        private static GenerationInput Input(SelectionRules selection = null) => new GenerationInput(new[] { typeof(FixtureMarker).Assembly }, c_Host, NamingStyle.Exact, selection, "test");

        private static GenerationContext NewContext() => new GenerationContext(Input());

        private static Type Fixture(string name) => typeof(FixtureMarker).Assembly.GetType("UnityInternalsFixture." + name, true);

        private static GeneratedFile File(GenerationResult result, string relativePath)
        {
            var file = result.Files.FirstOrDefault(f => f.RelativePath == relativePath);
            Assert.IsNotNull(file, "Missing file " + relativePath + "; have: " + string.Join(", ", result.Files.Select(f => f.RelativePath)));
            return file;
        }

        private static void AssertContainsLine(GeneratedFile file, string line)
        {
            Assert.IsTrue(file.Content.Split('\n').Contains(line), "Missing line:\n" + line + "\n--- in ---\n" + file.Content);
        }

        private static ReportEntry Entry(GenerationResult result, string id)
        {
            var entry = result.Entries.FirstOrDefault(e => e.Id == id);
            Assert.IsNotNull(entry, "No entry for " + id);
            return entry;
        }

        private static string MemberIdOf(string type, string member) => MemberId.Member(Fixture(type).GetMember(member, c_Declared).Single());

        private static SelectionRules Only(params string[] ids) => new SelectionRules(ids, Array.Empty<string>());

        [Test]
        public void StaticHost_File_ExactContent()
        {
            Assert.AreEqual(c_ApiFile, File(Generate(), "WrappedUnityInternalsFixture/PublicApi.g.cs").Content);
        }

        [Test]
        public void StaticHost_PublicMembers_NotMirrored()
        {
            StringAssert.DoesNotContain("Visible", File(Generate(), "WrappedUnityInternalsFixture/PublicApi.g.cs").Content);
        }

        [Test]
        public void InternalNestedType_EmittedInsideThePublicWrapper()
        {
            Assert.AreEqual(c_HostFile, File(Generate(), "WrappedUnityInternalsFixture/PublicHost.g.cs").Content);
            CollectionAssert.DoesNotContain(Generate().Files.Select(f => f.RelativePath).ToList(), "WrappedUnityInternalsFixture/InnerMode.g.cs");
        }

        [Test]
        public void StructHost_File_ExactContent_WithBothConversions()
        {
            Assert.AreEqual(c_SpotFile, File(Generate(), "WrappedUnityInternalsFixture/PublicSpot.g.cs").Content);
        }

        [Test]
        public void InstanceHost_MirrorsOnlyInternalMembers()
        {
            var file = File(Generate(), "WrappedUnityInternalsFixture/PublicThing.g.cs");

            AssertContainsLine(file, "        internal readonly global::UnityInternalsFixture.PublicThing m_Value;");
            AssertContainsLine(file, "        internal static PublicThing Wrap(global::UnityInternalsFixture.PublicThing value) => value == null ? null : new PublicThing(value);");
            AssertContainsLine(file, "        public global::UnityInternalsFixture.PublicThing Target => m_Value;");
            AssertContainsLine(file, "        public static implicit operator global::UnityInternalsFixture.PublicThing(PublicThing wrapper) => wrapper?.m_Value;");
            AssertContainsLine(file, "        public static implicit operator PublicThing(global::UnityInternalsFixture.PublicThing value) => Wrap(value);");
            AssertContainsLine(file, "        public int Size { get => m_Value.Size; set => m_Value.Size = value; }");
            AssertContainsLine(file, "        public static int Counter { get => global::UnityInternalsFixture.PublicThing.Counter; set => global::UnityInternalsFixture.PublicThing.Counter = value; }");
            AssertContainsLine(file, "        public string Label { get => m_Value.Label; set => m_Value.Label = value; }");
            AssertContainsLine(file, "        public int Doubled => m_Value.Doubled;");
            AssertContainsLine(file, "        public int Shared => m_Value.Shared;");
            AssertContainsLine(file, "        public int this[int index] => m_Value[index];");
            AssertContainsLine(file, "        public PublicThing(int size) : this(new global::UnityInternalsFixture.PublicThing(size)) { }");
            AssertContainsLine(file, "        public int Grow(int by) => m_Value.Grow(by);");
            AssertContainsLine(file, "        public static int Make(int size) => global::UnityInternalsFixture.PublicThing.Make(size);");

            foreach (var name in new[] { "PublicField", "PublicProperty", "PublicMethod", "Family", "Hidden" })
            {
                StringAssert.DoesNotContain(name, file.Content);
            }
        }

        [Test]
        public void InstanceHost_MemberOfAWrappedType_CrossesTheBoundary()
        {
            AssertContainsLine(File(Generate(), "WrappedUnityInternalsFixture/PublicThing.g.cs"),
                "        public global::WrappedUnityInternalsFixture.Point Corner { get => global::WrappedUnityInternalsFixture.Point.Wrap(m_Value.Corner); set => m_Value.Corner = (value).m_Value; }");
        }

        [Test]
        public void PublicTypeNestedInPublicType_NestsTheSameWay()
        {
            var file = File(Generate(), "WrappedUnityInternalsFixture/PublicOuter.g.cs");

            AssertContainsLine(file, "    public static class PublicOuter");
            AssertContainsLine(file, "        public static class PublicInner");
            AssertContainsLine(file, "            public static int Depth() => global::UnityInternalsFixture.PublicOuter.PublicInner.Depth();");
            CollectionAssert.DoesNotContain(Generate().Files.Select(f => f.RelativePath).ToList(), "WrappedUnityInternalsFixture/PublicInner.g.cs");
        }

        /// <summary>Target is the wrapped type itself, not its first public base as for an internal wrapper.</summary>
        [Test]
        public void DerivedPublicHost_TargetIsTheTypeItself()
        {
            AssertContainsLine(File(Generate(), "WrappedUnityInternalsFixture/PublicDerived.g.cs"),
                "        public global::UnityInternalsFixture.PublicDerived Target => m_Value;");
        }

        /// <summary>The base's internal members belong to the base's own wrapper; wrappers of public types do not inherit one another.</summary>
        [Test]
        public void PublicHosts_AreRoots_AndDoNotShareMembers()
        {
            var derived = File(Generate(), "WrappedUnityInternalsFixture/PublicDerived.g.cs");

            AssertContainsLine(derived, "    public class PublicDerived");
            AssertContainsLine(derived, "        public int Own => m_Value.Own;");
            StringAssert.DoesNotContain("Describe", derived.Content);
            AssertContainsLine(File(Generate(), "WrappedUnityInternalsFixture/FixtureNode.g.cs"), "        public string Describe() => m_Value.Describe();");
        }

        [Test]
        public void PublicBaseOfAnInternalWrapper_StillReadsAsThePublicType()
        {
            AssertContainsLine(File(Generate(), "WrappedUnityInternalsFixture/Branch.g.cs"), "        public global::UnityInternalsFixture.FixtureNode Target => m_Value;");
        }

        [Test]
        public void PublicHostWrapper_IsNotRegistered()
        {
            var registry = File(Generate(), "WrappedRuntime/WrapperRegistry.g.cs").Content;

            StringAssert.Contains("typeof(global::UnityInternalsFixture.Branch)", registry);
            StringAssert.DoesNotContain("PublicThing", registry);
            StringAssert.DoesNotContain("FixtureNode", registry);
        }

        [Test]
        public void ReservedName_OnAPublicHost_IsNameCollision()
        {
            var result = Generate();

            Assert.AreEqual(WrapStatus.NameCollision, Entry(result, MemberIdOf("PublicReserved", "Target")).Status);
            Assert.AreEqual("Name reserved by the wrapper 'Target'", Entry(result, MemberIdOf("PublicReserved", "Target")).Reason);
            Assert.AreEqual(WrapStatus.Wrapped, Entry(result, MemberIdOf("PublicReserved", "Fine")).Status);
        }

        [Test]
        public void ContainerWithNothingEmittable_ProducesNoFile()
        {
            var result = Generate();

            Assert.AreEqual(WrapStatus.Wrapped, Entry(result, MemberId.Type(Fixture("PublicPrivateNest"))).Status);
            CollectionAssert.DoesNotContain(result.Files.Select(f => f.RelativePath).ToList(), "WrappedUnityInternalsFixture/PublicPrivateNest.g.cs");
        }

        /// <summary>The known catalog issue: a private nested type of a public type now hangs under that type, not under its namespace.</summary>
        [Test]
        public void PrivateNestedTypeOfAPublicType_ParentIsThePublicType()
        {
            var catalog = CatalogBuilder.Build(NewContext());
            var host = MemberId.Type(Fixture("PublicPrivateNest"));
            var secret = catalog.Get(MemberId.Type(Fixture("PublicPrivateNest").GetNestedType("Secret", BindingFlags.NonPublic)));

            Assert.IsNotNull(catalog.Get(host));
            Assert.IsNotNull(secret);
            Assert.AreEqual(host, secret.ParentId);
            Assert.AreEqual(WrapStatus.NotAccessible, secret.Status);
        }

        [Test]
        public void PublicTypeWithoutInternals_IsNotInTheCatalog()
        {
            Assert.IsFalse(CatalogBuilder.Build(NewContext()).Contains(MemberId.Type(typeof(FixtureMarker))));
        }

        [Test]
        public void DeferralReason_IsGoneFromReportAndCatalog()
        {
            var result = Generate();

            CollectionAssert.IsEmpty(result.Entries.Where(e => e.Reason != null && e.Reason.Contains(c_RetiredReason)).Select(e => e.Id).ToList());
            CollectionAssert.IsEmpty(result.Catalog.Nodes.Where(n => n.Reason != null && n.Reason.Contains(c_RetiredReason)).Select(n => n.Id).ToList());
        }

        [Test]
        public void SelectingAMember_EmitsItAndAutoIncludesTheTypesItNeeds()
        {
            var corner = MemberIdOf("PublicThing", "Corner");
            var result = Generate(Only(corner));

            CollectionAssert.AreEqual(new[] { "WrappedUnityInternalsFixture/Point.g.cs", "WrappedUnityInternalsFixture/PublicThing.g.cs" }, result.Files.Select(f => f.RelativePath).ToList());
            CollectionAssert.AreEqual(new[] { corner }, result.Selection.EmittedMemberIds);
            CollectionAssert.Contains(result.Selection.AutoIncludedBy.Keys, MemberId.Type(Fixture("Point")));
        }

        [Test]
        public void SelectingTheType_SelectsEveryMemberBeneathIt()
        {
            var result = Generate(Only(MemberId.Type(Fixture("PublicThing"))));
            var emitted = result.Selection.EmittedMemberIds;

            CollectionAssert.Contains(emitted, MemberIdOf("PublicThing", "Grow"));
            CollectionAssert.Contains(emitted, MemberIdOf("PublicThing", "Make"));
            CollectionAssert.Contains(emitted, MemberIdOf("PublicThing", "Shared"));
            Assert.IsFalse(emitted.Any(id => id.Contains("PublicMethod")), "a public member is not selectable");
        }

        /// <summary>The known issue: this used to read "Declaring type is Deferred" because the public type node never became Wrapped.</summary>
        [Test]
        public void SelectedMemberAbsentFromThisUnity_IsSelectedMissing()
        {
            var gone = MemberId.Type(Fixture("PublicApi")).Replace("|Type|PublicApi", "|Method|Gone()");
            var entry = Entry(Generate(Only(gone)), gone);

            Assert.AreEqual(WrapStatus.SelectedMissing, entry.Status);
            Assert.AreEqual("selected id not found in current Unity", entry.Reason);
        }

        [Test]
        public void TwoRuns_ProduceIdenticalOutput()
        {
            var a = Generate();
            var b = Generate();

            CollectionAssert.AreEqual(a.Files.Select(f => f.RelativePath).ToList(), b.Files.Select(f => f.RelativePath).ToList());
            for (var i = 0; i < a.Files.Count; i++)
            {
                Assert.AreEqual(a.Files[i].Content, b.Files[i].Content, a.Files[i].RelativePath);
            }
            CollectionAssert.AreEqual(a.Entries.Select(e => e.Id + "/" + e.Status + "/" + e.Reason).ToList(), b.Entries.Select(e => e.Id + "/" + e.Status + "/" + e.Reason).ToList());
        }
    }
}
